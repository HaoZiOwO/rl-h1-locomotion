"""
train.py — 用 PPO 训练 Humanoid-v4 双足人形机器人行走

跑完会生成 ppo_humanoid.zip，用 play.py 回放看它走路
"""

# ============================================================
# 第1行：从 stable_baselines3 库导入 PPO 算法类
# PPO = Proximal Policy Optimization（近端策略优化）
# 这是目前强化学习里最主流、最稳定的策略梯度算法
# SB3 帮你封装好了：数据采集、GAE 计算、网络更新、clip 机制——全自动
# ============================================================
from stable_baselines3 import PPO

# ============================================================
# 第2行：导入 gymnasium —— 强化学习的标准环境接口库
# gymnasium 是 OpenAI Gym 的后继者，所有 RL 环境都遵循它的 API
# ============================================================
import gymnasium as gym

# ============================================================
# 第3行：创建环境
# "Humanoid-v4" 是 MuJoCo 物理引擎里的双足人形机器人
# 观测空间：376 维（关节角度 + 角速度 + 躯干姿态 + 惯性数据）
# 动作空间：17 维（控制髋、膝、踝等 17 个关节的力矩）
# 每步的 reward 包含：前进速度奖励 + 存活奖励 - 控制代价
# ============================================================
env = gym.make("Humanoid-v4")

# ============================================================
# 第4行：创建 PPO 模型
#
# "MlpPolicy" —— 用多层感知机（全连接网络）作为策略
#   输入 376 维观测 → 64层ReLU → 64层ReLU → 输出 17 维动作均值
#   同时还有一个独立的 value network 估计状态价值
#
# env —— 告诉模型环境的观测/动作维度
#
# verbose=1 —— 训练时打印日志（就是屏幕上刷的那些数字）
#
# tensorboard_log="./logs/" ——
#   把 reward、loss 等数据写入 logs 目录
#   之后用 `tensorboard --logdir logs` 就能看到训练曲线
# ============================================================
model = PPO("MlpPolicy", env, verbose=1, tensorboard_log="./logs/")

# ============================================================
# 第5行：开始训练
#
# total_timesteps=2_000_000 —— 让 Humanoid 在仿真里走 200 万步
#   每 2048 步采集一批数据 → 计算 GAE 优势 → 更新网络 → 重复
#   200 万步大约需要 1-2 小时（取决于 GPU 和 CPU）
#
# 内部流程（你不需要写任何一行）：
#   1. 用当前策略在环境里跑 2048 步，收集 (s,a,r,s')
#   2. 用 GAE（广义优势估计）算每个动作的 advantage
#   3. 用 clip 机制更新策略网络（限制新旧策略差异）
#   4. 用 MSE loss 更新价值网络
#   5. 回到步骤 1
# ============================================================
model.learn(total_timesteps=2_000_000)

# ============================================================
# 第6行：保存模型
# 生成 ppo_humanoid.zip —— 包含策略网络和价值网络的权重
# 之后用 PPO.load("ppo_humanoid") 就能加载回来
# ============================================================
model.save("ppo_humanoid")

print("Training done. Model saved as ppo_humanoid.zip")
